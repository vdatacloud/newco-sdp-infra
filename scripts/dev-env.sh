#!/bin/sh
# Create local/.env.<env> once with generated dev-only credentials (gitignored, never committed).
# Usage: scripts/dev-env.sh [env]   (default env: dev)
set -eu
env=${1:-dev}
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/local/.env.$env"
[ -f "$out" ] && { echo "$out exists; delete it (and run deps-reset) to regenerate"; exit 0; }
umask 077
key() { openssl rand -base64 64 | tr -d '\n'; }
accounts=""
for prefix in $(jq -r '.accounts[].prefix' "$root/config/storage-accounts.json"); do
  accounts="${accounts:+$accounts;}${prefix}${env}:$(key)"
done
{
  echo "# Generated by scripts/dev-env.sh for the sdp-$env stack. Dev-only credentials; never commit."
  echo "SDP_ENV=$env"
  echo "POSTGRES_DB=sdp_$env"
  echo "POSTGRES_USER=sdp_admin"
  echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
  echo "AZURITE_ACCOUNTS='$accounts'"
} > "$out"
echo "wrote $out"
