#!/bin/sh
# Create local/.env.<env> once with generated dev-only secrets (gitignored, never committed).
# Non-secret values come from config/environments/<env>.yaml (scripts/env-render.sh).
# Usage: scripts/dev-env.sh [env]   (default env: dev)
set -eu
env=${1:-dev}
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/local/.env.$env"
[ -f "$out" ] && exit 0
umask 077
key() { openssl rand -base64 64 | tr -d '\n'; }
accounts=""
for prefix in $(cd "$root" && yq '.storage.accounts[].prefix' "config/environments/$env.yaml"); do
  accounts="${accounts:+$accounts;}${prefix}${env}:$(key)"
done
{
  echo "# Generated by scripts/dev-env.sh for the sdp-$env stack. Dev-only secrets; never commit."
  echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
  echo "AZURITE_ACCOUNTS='$accounts'"
} > "$out"
echo "wrote $out"
