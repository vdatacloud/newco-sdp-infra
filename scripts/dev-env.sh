#!/bin/sh
# Create or extend local/.env.<env> with generated dev-only secrets (gitignored, never committed).
# Each key is generated once; a key added in a later phase is appended to an existing file, and
# existing values are never changed. Non-secret values come from config/environments/<env>.yaml.
# Usage: scripts/dev-env.sh [env]   (default env: dev)
set -eu
env=${1:-dev}
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/local/.env.$env"
umask 077
key() { openssl rand -base64 64 | tr -d '\n'; }
has() { [ -f "$out" ] && grep -q "^$1=" "$out"; }
add() { has "$1" || { echo "$1=$2" >> "$out"; added="$added $1"; }; }

added=""
[ -f "$out" ] || echo "# Generated by scripts/dev-env.sh for the sdp-$env stack. Dev-only secrets; never commit." > "$out"
add POSTGRES_PASSWORD "$(openssl rand -hex 24)"
if ! has AZURITE_ACCOUNTS; then
  accounts=""
  for prefix in $(cd "$root" && yq '.storage.accounts[].prefix' "config/environments/$env.yaml"); do
    accounts="${accounts:+$accounts;}${prefix}${env}:$(key)"
  done
  add AZURITE_ACCOUNTS "'$accounts'"
fi
# I2b: Keycloak bootstrap admin (Terraform applies the realms with it).
add KEYCLOAK_ADMIN_PASSWORD "$(openssl rand -hex 24)"
[ -z "$added" ] || echo "wrote$added to $out"
